ENT.Category = "Bloodshed"
ENT.Spawnable = false

ENT.IsBloodshedHuman = true

ENT.Faction = "police"

-- Люди смотрят вперёд, а не по кругу: обойти со спины должно работать.
ENT.SightAngle = 150
ENT.HearingDistance = 3000

-- Шаг намеренно медленный: на 90 ноги мелькали, патруль выглядел бегущим.
ENT.WalkSpeed = 55
ENT.RunSpeed = 200

ENT.EyeHeight = 64
ENT.CollisionMins = Vector(-16, -16, 0)
ENT.CollisionMaxs = Vector(16, 16, 72)

ENT.RandomSkins = true
ENT.RandomBodygroups = true

--------------------------------------------------------------------------------
-- Оружие
--------------------------------------------------------------------------------

ENT.WeaponAttachment = "anim_attachment_rh"

-- Какой набор анимаций у модели: "citizen" или "combine". См. MuR.NPC.AnimSets.
ENT.AnimSet = "citizen"

-- Чем вооружаться, если оружие не задано явно при спавне.
ENT.DefaultWeapons = nil

-- На какой дистанции держаться от цели с огнестрелом. Полиция меняет её на ходу.
ENT.Weapon_RetreatDistance = 125
-- Ближе этого стрелять неудобно — бьём прикладом.
ENT.Weapon_MeleeDistance = 70
-- Дальше этого не стреляем (масштабируется rangeScale оружия).
ENT.Weapon_Range = 2200
-- Разброс умножается на это: 1 — как в описании оружия, больше — хуже стрелок.
ENT.Weapon_Accuracy = 1
-- Множитель урона пуль: 1 — как в описании оружия. Оружие описано данными,
-- общими для нескольких NPC (ЧВК и SWAT делят одни TFA-стволы), поэтому сила
-- стрелка регулируется здесь, а не в данных ствола.
ENT.Weapon_DamageScale = 1
-- Пауза между очередями.
ENT.Weapon_RestTime = {0.4, 1.2}
-- Стрелять на ходу в переходах (FollowPath с fire = true). Работает только у
-- скелетов с жестовой стрельбой: у остальных выстрел ставит активити на всё
-- тело и остановил бы ноги.
ENT.CanShootWhileMoving = true
-- Доля магазина, ниже которой боец начинает искать укрытие заранее, а не когда
-- ствол уже щёлкнул.
ENT.LowAmmoFraction = 0.35

--------------------------------------------------------------------------------
-- Тактика
--------------------------------------------------------------------------------

-- Люди прячутся, в отличие от тварей.
ENT.CanUseCover = true
-- Насколько близко к найденному углу надо подойти, чтобы считать себя в укрытии.
ENT.CoverReachedDist = 48
--
-- Ближе этого за углы не бегают. Было 260 — и это отсекало поиск укрытия ровно
-- на тех дистанциях, где и идут перестрелки: замерено, ShouldSeekCover отказывал
-- 10 раз из 11 при дистанции боя около 200.
--
-- Сорок — это уже рукопашная (Weapon_MeleeDistance = 70): там решает приклад, а
-- не угол. От отхода спиной под ствол защищает не этот порог, а требование
-- GoToCover брать угол не ДАЛЬШЕ от цели, чем текущее место.
--
ENT.CoverMinEngageDistance = 40
-- Насколько дальше от цели, чем текущее место, разрешено брать угол. Полшага
-- назад за выступ — нормально; отбежать на два корпуса — уже отход под ствол.
ENT.CoverBackstepAllowance = 220
-- Пауза перед выстрелом из-за низкого укрытия: боец привстаёт, а не выпрыгивает.
ENT.CoverPopUpDelay = 0.15
-- Сколько сидеть пригнувшись между очередями.
ENT.CoverDuckTime = {0.7, 1.6}
-- Сколько держать паузу, ничего не предпринимая за укрытием.
ENT.CoverHoldTime = {0.8, 2.0}
-- Насколько роль "assault" добавляет веса рывку вперёд. Не замена остальным
-- действиям, а перевес: боец идёт первым, но по дороге отстреливается.
--
-- Было 60 — и отряд штурмовал слишком напористо, укрытие превращалось в
-- пересадочную станцию. Двадцать пять оставляют взявшему роль заметный перевес
-- к наступлению, не отменяя выглядывание и огонь с места.
ENT.AssaultAdvanceBoost = 25
-- Огонь вслепую из-за края: ствол показывается, голова нет.
ENT.CanBlindFire = true
-- Во сколько раз хуже разброс при стрельбе вслепую. Задача не убить, а не дать
-- поднять голову.
ENT.CoverBlindSpread = 3
-- Приставной шаг вдоль укрытия: длина и потолок времени на него.
ENT.CoverSlideDistance = {64, 140}
ENT.CoverSlideTime = 1.5

-- Уходить от прилетевших гранат. Радиус чуть больше поражения: уйти надо за
-- границу, а не встать ровно на неё.
ENT.AvoidsGrenades = true
ENT.DangerRadius = 300
ENT.DangerScanInterval = 0.4
ENT.DangerFleeTime = 2.5

-- У стрелков коридор огня проверяется всегда.
ENT.CheckLineOfFire = true

-- Прицеливание поз-параметрами. Скорость доводки в долях в секунду: 8 означает
-- «доходит до цели примерно за восьмую секунды».
ENT.AimPoseRate = 8
-- Насколько голова доворачивается дальше плеч.
ENT.AimHeadLead = 0.6
-- Сколько ещё держать на прицеле место, где цель скрылась.
ENT.AimHoldTime = 3

--
-- Манера наступления:
--   "rush"  — идёт на цель напрямую;
--   "bound" — перебежками от угла к углу, с паузами на огонь;
--   "hold"  — не наступает вовсе, пока цель показывается: сидит и стреляет.
--
ENT.AdvanceStyle = "rush"
-- Тяжёлые не пятятся от подошедшего вплотную.
ENT.Weapon_HoldsGround = false
--
-- Доля Weapon_RetreatDistance, ниже которой боец начинает пятиться.
--
-- Разнос порогов, а не одно число: сближение подводит ровно на
-- Weapon_RetreatDistance, и совпадение порогов давало колебание вперёд-назад
-- вместо боя. Между 0.6 и 1.0 дистанции боец стоит и стреляет.
--
ENT.RetreatHysteresis = 0.6
-- Как часто вообще позволено разрывать дистанцию. Боевая корутина крутится
-- примерно раз в секунду, и без отката отход шёл бы непрерывно.
ENT.BackAwayInterval = {3, 5}
-- Сколько сближений подряд без сдвига дистанции считать залипанием.
ENT.PressIdleLimit = 3
-- Насколько дистанция должна измениться, чтобы считать заход не холостым.
ENT.PressProgressEpsilon = 64
-- Сколько секунд после попадания в тебя любая манера превращается в бег.
ENT.HurtRunTime = 6

-- Огонь по месту, где цель видели в последний раз.
ENT.CanSuppress = true
-- Дольше этого наводка для подавления не годится: стрелять в угол, за которым
-- никого нет уже полминуты, — не подавление, а трата магазина.
ENT.SuppressMemoryTime = 4
ENT.SuppressInterval = {2.5, 4.5}

-- Сколько держащий позицию ждёт цель, прежде чем всё-таки пойти её искать.
ENT.HoldPatience = 12

-- Наступление перебежками: длина рывка и пауза между рывками.
ENT.BoundDistance = 550
-- Насколько рывок обязан сократить дистанцию, чтобы считаться наступлением.
ENT.BoundMinGain = 150
ENT.BoundPause = {1.2, 2.5}

-- Шаг вбок между очередями: не тактика, а «не стоять столбом».
ENT.StrafeDistance = {90, 170}
ENT.StrafeChance = 25
-- Как часто менять огневую позицию целиком.
ENT.RepositionInterval = {7, 13}

ENT.CanWander = true
ENT.WanderRadius = 1200
ENT.WanderInterval = {4, 10}
ENT.UnreachablePause = 1
-- На каком расстоянии держаться, когда приказано следовать.
ENT.FollowDistance = 150

